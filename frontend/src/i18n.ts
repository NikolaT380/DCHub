export const formatDate = (dateString?: string, lang: 'mk' | 'en' = 'mk'): string => {
    if (!dateString) return '-';
    const date = new Date(dateString);
    return date.toLocaleDateString(lang === 'mk' ? 'mk-MK' : 'en-US', {
        year: 'numeric',
        month: 'short',
        day: 'numeric',
        hour: '2-digit',
        minute: '2-digit'
    });
};

export const truncateText = (text: string | null | undefined, maxChars: number, preserveWords: boolean = false): string => {
    if (!text) return '';
    if (text.length <= maxChars) return text;

    if (preserveWords) {
        const trimmed = text.slice(0, maxChars);
        const lastSpace = trimmed.lastIndexOf(' ');
        if (lastSpace > 0) {
            return trimmed.slice(0, lastSpace) + '...';
        }
    }

    return text.slice(0, maxChars) + '...';
};
